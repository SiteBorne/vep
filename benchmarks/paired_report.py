"""Render benchmarks/results/paired-*.json as docs/BENCHMARK_RESULTS_PAIRED.md (no interpretation beyond the preregistered verdicts)."""
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
import argparse

OUT = ROOT / "docs" / "BENCHMARK_RESULTS_PAIRED.md"
DEFAULT_DIR = ROOT / "benchmarks" / "results"


def row(cells):
    return "| " + " | ".join(str(c) for c in cells) + " |"


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--dir", default=str(DEFAULT_DIR), help="directory holding paired-<project>.json")
    ap.add_argument("--out", default=str(OUT))
    ap.add_argument("--title", default="Paired benchmark results (controlled run)")
    ap.add_argument("--note", default="")
    args = ap.parse_args()
    out_path, res_dir = Path(args.out), Path(args.dir)
    L = [f"# {args.title}", "", *([args.note, ""] if args.note else []),
         "Generated by `benchmarks/paired_report.py` from `benchmarks/results/paired-*.json`. Thresholds, verdict rule and procedures: "
         "[BENCHMARK_METHODOLOGY](BENCHMARK_METHODOLOGY.md). Each comparison shows the **preregistered Welch verdict** (headline) and the paired-bootstrap verdict. "
         "Times are wall-clock seconds; `d` is the mean paired difference (VEP minus baseline); intervals are 95%.", ""]
    for proj in ("pyflakes", "more-itertools"):
        p = res_dir / f"paired-{proj}.json"
        if not p.exists():
            L += [f"## {proj}", "NOT_RUN: no paired report exists.", ""]
            continue
        d = json.loads(p.read_text())
        L += [f"## {proj} (pinned `{d['pinned_commit'][:12]}`, VEP `{d['vep_commit'][:12]}`)",
              f"Host: {d['host']['platform']}, {d['host']['cpus']} logical CPUs, Python {d['host']['python']}; power: {d['host']['power']}; swap: {d['host']['swap']}. "
              f"Load average (1 min) at start: **{d['load_avg_1m_at_start']:.2f}** (the gate's declared criterion is < 2.0). Correctness gate: {'all configurations accept the clean tree and reject the mutant' if not d['gate_failures'] else 'FAILURES: ' + str(d['gate_failures'])}.", ""]
        for sc, v in d["scenarios"].items():
            env = v["environment"]
            idle_ok = sum(1 for b in v["blocks"] if (b["env"]["cpu_idle_pct"] or 0) >= 75)
            cv_ok = env["direct_baseline_cv"] is not None and env["direct_baseline_cv"] <= 0.05
            env_valid = idle_ok >= 0.9 * len(v["blocks"]) and cv_ok
            L += [f"### {sc}", f"Valid blocks: {v['valid_blocks']} (warmups {len(v['warmup_blocks'])}, excluded {len(v['excluded'])}). "
                  f"Environment during blocks: load avg {env['load_avg_1m_min']}-{env['load_avg_1m_max']}, minimum CPU idle {env['cpu_idle_pct_min']}%, direct-baseline CV "
                  f"{env['direct_baseline_cv']}. Reporting-only validity: CPU idle >= 75% in {idle_ok}/{len(v['blocks'])} blocks, direct CV <= 5%: {'yes' if cv_ok else 'NO'} => **environment {'valid' if env_valid else 'NOT valid'} by the declared reporting criteria**. Not applicable: {v['not_applicable'] or 'none'}.", "",
                  row(["Config", "wall mean", "median", "sd", "CPU mean", "peak RSS MB", "cache hits/misses"]), row(["---"] * 7)]
            for c, a in v["analysis"]["configs"].items():
                L.append(row([c, a["wall_s"]["mean"], a["wall_s"]["median"], a["wall_s"]["sd"], a["cpu_s"]["mean"], a["peak_child_rss_mb"]["mean"],
                              f"{a.get('cache_hits', '-')}/{a.get('cache_misses', '-')}"]))
            L += ["", row(["Comparison (VEP vs baseline)", "Welch verdict (preregistered)", "rel diff [95% CI]", "bootstrap verdict", "d mean [95% CI] s", "CPU ratio"]), row(["---"] * 6)]
            for k, c in v["analysis"]["comparisons"].items():
                w, b = c["welch_preregistered"], c["paired_bootstrap"]
                L.append(row([k.replace("_vs_", " vs "), w["verdict"], f"{w['rel_diff']:+.1%} [{w['rel_ci95'][0]:+.1%}, {w['rel_ci95'][1]:+.1%}]", b["verdict"],
                              f"{b['mean_paired_diff_s']:+.3f} [{b['diff_ci95_s'][0]:+.3f}, {b['diff_ci95_s'][1]:+.3f}]", c["cpu_mean_ratio"]]))
            if v["excluded"]:
                L += ["", "Excluded blocks: " + "; ".join(f"#{e.get('index', e.get('block'))}: {e.get('excluded_reason', e.get('reason'))}" for e in v["excluded"])]
            L.append("")
    out_path.write_text("\n".join(L) + "\n")
    print("wrote", out_path)
    return 0


if __name__ == "__main__":
    sys.exit(main())
