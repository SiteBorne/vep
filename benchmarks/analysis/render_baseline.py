"""Render docs/AGENT_SCALE_PERFORMANCE_BASELINE.md from master-dataset.json (every number comes from the dataset; nothing is typed by hand).

    python benchmarks/analysis/render_baseline.py [--check]
"""
from __future__ import annotations

import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
D = json.loads((ROOT / "benchmarks/analysis/master-dataset.json").read_text())
OUT = ROOT / "docs" / "AGENT_SCALE_PERFORMANCE_BASELINE.md"
SRC = {s["path"]: s for s in D["sources"]}


def obs(**kw):
    return [o for o in D["observations"] if all(o.get(k) == v for k, v in kw.items())]


def f(x, n=3):
    return "-" if x is None else f"{x:.{n}f}"


def paired_table(path: str) -> list[str]:
    s = SRC[path]
    rows = [f"### `{path}`", f"Cohort `{s['cohort']}` · {s['classification']} · project {s['project']} @ `{(s['project_commit'] or '')[:8]}` · VEP `{(s['vep_commit'] or '')[:8]}` · sha256 `{s['sha256'][:12]}`",
            f"Host: {s['host'].get('platform')}, {s['host'].get('cpus')} cpus{', ' + s['host']['cpu_model'] if s['host'].get('cpu_model') else ''}, load avg at start {s['host'].get('load_avg_1m_at_start')}. {s['note']}", "",
            "| Scenario | Config | Assurance | wall mean [95% CI] s | wall median | CPU mean s | peak RSS MB | n (warmups) |", "|---|---|---|---|---|---|---|---|"]
    for sc in sorted({o["scenario"] for o in D["observations"] if o["source_path"] == path}):
        for cfg in sorted({o["config"] for o in D["observations"] if o["source_path"] == path and o["scenario"] == sc}):
            w = [o for o in D["observations"] if o["source_path"] == path and o["scenario"] == sc and o["config"] == cfg]
            by = {o["metric"]: o for o in w}
            ci = by["wall_s"]["confidence_interval"]
            rows.append(f"| {sc} | {cfg} | {by['wall_s']['assurance']} | {f(by['wall_s']['stats']['mean'], 4)} [{f(ci['lo'], 4)}, {f(ci['hi'], 4)}] | {f(by['wall_s']['stats']['median'], 4)} | "
                        f"{f(by['cpu_s']['stats']['mean'], 4)} | {f(by['peak_child_rss_mb']['stats']['mean'], 1)} | {by['wall_s']['samples_n']} ({by['wall_s']['warmups']}) |")
    rows += ["", "| Scenario | Comparison (VEP minus baseline) | preregistered Welch verdict | rel diff [95% CI] | bootstrap verdict | CPU ratio |", "|---|---|---|---|---|---|"]
    for c in D["comparisons"]:
        if c["source_path"] == path:
            w, bt = c["welch_preregistered"], c["paired_bootstrap"]
            rows.append(f"| {c['scenario']} | {c['comparison']} | {w['verdict']} | {f(w['rel_diff'] * 100, 1)}% [{f(w['rel_ci95'][0] * 100, 1)}%, {f(w['rel_ci95'][1] * 100, 1)}%] | {bt['verdict'] if bt else '-'} | {c['cpu_mean_ratio'] if c['cpu_mean_ratio'] is not None else '-'} |")
    return rows + [""]


def render() -> str:
    L = ["# Agent-scale performance baseline (generated; do not edit)", "",
         "Generated by `benchmarks/analysis/render_baseline.py` from [`master-dataset.json`](../benchmarks/analysis/master-dataset.json) (validated by `benchmarks/analysis/validate.py`; inventory: [`benchmark-inventory.csv`](../benchmarks/analysis/benchmark-inventory.csv)). "
         f"{len(D['sources'])} sources, {len(D['observations'])} observations, {len(D['comparisons'])} comparisons. **Cohorts are never averaged together.** Assurance levels are different contracts and are shown on every row: "
         "a plain test run gives an exit code; testmon is heuristic selection; a build-cache hit is a lookup without a certificate; a derived attestation names original evidence; only the protected workflow issues a fresh certificate.", "",
         "## Assurance levels", ""] + [f"* `{k}`: {v}" for k, v in D["assurance_levels"].items()] + ["", "## Classification of each source", "",
         "| Source | Kind | Classification | Cohort | Note |", "|---|---|---|---|---|"]
    for s in D["sources"]:
        if s["kind"] in ("hosted_run_artifact",):
            continue
        L.append(f"| `{s['path']}` | {s['kind']} | **{s['classification']}** | {s['cohort']} | {s['note'][:150]} |")
    L += ["", "## Principal portable baseline: GitHub-hosted ubuntu-24.04, valid environment (MEASURED)", ""]
    for p in ("benchmarks/results/hosted-linux/paired-pyflakes.json", "benchmarks/results/hosted-linux/paired-more-itertools.json"):
        L += paired_table(p)
    L += ["## Separate cohort: local macOS arm64 (paired run; INVALID_ENVIRONMENT by its own declared criteria)", "",
          "Load average about 5 and minimum CPU idle about 60% at the time: the run does not meet the declared reporting criteria, so it is not a quiet-machine result. It is shown as a separate cohort, never merged with the hosted numbers.", ""]
    for p in ("benchmarks/results/paired-pyflakes.json", "benchmarks/results/paired-more-itertools.json"):
        L += paired_table(p)
    L += ["## Controller scaling (macOS local cohort, MEASURED, tiny jobs)", "", "| Setting | throughput jobs/s mean (sd) | wall mean s | mean latency s | child CPU s per rep | peak child RSS MB |", "|---|---|---|---|---|---|"]
    for cfg in ("direct_sequential_no_controller", "controller_1_workers", "controller_2_workers", "controller_4_workers", "controller_8_workers", "controller_16_workers"):
        r = {o["metric"]: o for o in obs(config=cfg)}
        L.append(f"| {cfg} | {f(r['throughput_jobs_per_s']['stats']['mean'], 1)} ({f(r['throughput_jobs_per_s']['stats'].get('stdev'), 1)}) | {f(r['wall_s']['stats']['mean'], 3)} | "
                 f"{f(r['mean_latency_s']['stats']['mean'], 3) if 'mean_latency_s' in r else '-'} | {f(r['child_cpu_s']['stats']['mean'], 2) if 'child_cpu_s' in r else '-'} | {f(r['peak_single_child_rss_mb']['stats']['mean'], 1) if 'peak_single_child_rss_mb' in r else '-'} |")
    L += ["", "## Stage profiles (macOS local cohort, MEASURED, synthetic projects, inclusive medians)", "", "| Operation | 200 tests / 402 files (ms) | 1,000 tests / 2,002 files (ms) | Assurance |", "|---|---|---|---|"]
    ops = ["full_workflow", "derive_export_verify"] + sorted({o["operation"] for o in obs(scenario="stage_profile_200") if o["operation"].startswith("stage:")}, key=lambda k: -obs(scenario="stage_profile_1000", operation=k)[0]["stats"]["median"] if obs(scenario="stage_profile_1000", operation=k) else 0)
    for op in ops:
        a, b = obs(scenario="stage_profile_200", operation=op), obs(scenario="stage_profile_1000", operation=op)
        if a and b:
            L.append(f"| {op} | {f(a[0]['stats']['median'], 1)} | {f(b[0]['stats']['median'], 1)} | {a[0]['assurance']} |")
    L += ["", "## Other records", ""]
    for o in obs(scenario="object_parse_cache"):
        L.append(f"* Parse-cache experiment `{o['operation']}`: {o['samples']} ms ({o['limitations'][0]})")
    for o in obs(scenario="mcp"):
        L.append(f"* MCP `{o['operation']}`: {o['stats']}  {o['units']}")
    L += ["", "## Synthetic (SIMULATED, not measurements)", ""] + [f"* `{o['operation']}`: total cost {o['stats']['mean']} (assumed prices)" for o in obs(scenario="policy_simulation")]
    L += ["", "## Global limitations", ""] + [f"* {x}" for x in D["global_limitations"]] + [""]
    return "\n".join(L)


if __name__ == "__main__":
    text = render()
    if "--check" in sys.argv:
        sys.exit(0 if OUT.exists() and OUT.read_text() == text else 1)
    OUT.write_text(text)
    print(f"wrote {OUT} ({len(text.splitlines())} lines)")
