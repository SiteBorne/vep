"""Historical workspaces produced by earlier REAL builds must open, migrate and verify under the current code.

Fixtures: tests/fixtures/ws_v0_4_0a1/ (schema 2, generated by scripts/gen_v040_fixture.py from the v0.4.0a1 tag, no signing key)
and the frozen 0.3.0 layout used by tests/test_compat.py (schema 1).
"""
import hashlib
import json
import shutil
import sqlite3
import tempfile
import unittest
from pathlib import Path

from vep import certificates, controller, versions
from vep.errors import SchemaError
from vep.workspace import Workspace

FIX = Path(__file__).parent / "fixtures" / "ws_v0_4_0a1"


class V040FixtureTests(unittest.TestCase):
    def setUp(self):
        if not (FIX / "vep.sql").exists():
            self.skipTest("fixture not generated")
        self.m = json.loads((FIX / "manifest.json").read_text())
        self.tmp = Path(tempfile.mkdtemp())
        self.addCleanup(shutil.rmtree, self.tmp, True)
        self.root = self.tmp / "ws"
        (self.root / ".vep").mkdir(parents=True)
        db = sqlite3.connect(str(self.root / ".vep" / "vep.db"))
        db.executescript((FIX / "vep.sql").read_text())  # rebuild the original schema-2 database from its dump
        db.commit(); db.close()
        shutil.copytree(FIX / "cas", self.root / ".vep" / "cas")
        shutil.copytree(FIX / "project", self.root, dirs_exist_ok=True)

    def test_fixture_is_the_frozen_schema_2_original(self):
        self.assertEqual(hashlib.sha256((FIX / "vep.sql").read_bytes()).hexdigest(), self.m["vep_sql_sha256"])
        self.assertEqual((self.m["package_version"], self.m["db_schema"]), ("0.4.0a1", 2))
        c = sqlite3.connect(self.root / ".vep" / "vep.db")
        self.assertEqual(c.execute("select value from meta where key='schema_version'").fetchone()[0], "2")
        self.assertIsNone(c.execute("select name from sqlite_master where name='jobs'").fetchone())  # genuinely pre-controller
        c.close()

    def test_migrates_to_current_schema_additively_and_keeps_rows(self):
        before = sqlite3.connect(self.root / ".vep" / "vep.db")
        counts = {t: before.execute(f"select count(*) from {t}").fetchone()[0] for t in ("objects", "candidates", "evidence", "certificates", "transitions", "ledger")}
        before.close()
        ws = Workspace(self.root)
        with ws.db.read() as c:
            self.assertEqual(int(c.execute("select value from meta where key='schema_version'").fetchone()[0]), versions.DB_SCHEMA_VERSION)
            for t, n in counts.items():
                self.assertEqual(c.execute(f"select count(*) from {t}").fetchone()[0], n, t)
            for t in ("jobs", "job_events", "build_cache", "build_log"):
                self.assertEqual(c.execute(f"select count(*) from {t}").fetchone()[0], 0, t)
        Workspace(self.root)  # idempotent

    def test_published_certificate_still_verifies_with_original_trust_semantics(self):
        ws = Workspace(self.root)
        hist = certificates.verify_certificate(ws, self.m["certificate_id"])
        live = certificates.verify_certificate(ws, self.m["certificate_id"], current_root=self.root)
        for v in (hist, live):
            self.assertEqual((v["trust_level"], v["legacy_schema"], v["snapshot_id"]), ("TRUSTED_LOCAL", False, self.m["snapshot_id"]))
            self.assertEqual(v["evaluator_id"], self.m["evaluator_id"])
            self.assertTrue(v["evaluator_id"].startswith("vep-local-evaluator/0.4.0a1/"))
        with self.assertRaises(Exception):
            certificates.verify_certificate(ws, self.m["certificate_id"], require_trust="ISOLATED_VERIFIED")  # never upgraded

    def test_changed_source_is_still_rejected_and_bundle_verifies(self):
        from vep import conformance
        ws = Workspace(self.root)
        (self.root / "extra.py").write_text("X = 2\n")
        with self.assertRaises(Exception):
            certificates.verify_certificate(ws, self.m["certificate_id"], current_root=self.root)
        b = conformance.export_bundle(ws, self.m["certificate_id"])
        self.assertTrue(conformance.verify_bundle(b)["valid"])  # a 0.4.0a1 certificate passes the current bundle verifier

    @unittest.skipUnless(shutil.which("node"), "node not installed: independent verification of the old certificate NOT RUN")
    def test_independent_node_verifier_accepts_the_0_4_0a1_certificate(self):
        import subprocess
        from vep import conformance
        ws = Workspace(self.root)
        b = conformance.export_bundle(ws, self.m["certificate_id"])
        p = self.tmp / "bundle.json"
        p.write_text(json.dumps(b))
        r = subprocess.run(["node", str(Path(__file__).resolve().parents[1] / "conformance" / "node" / "verify.mjs"), "bundle", str(p)], capture_output=True, text=True)
        out = json.loads(r.stdout)
        self.assertTrue(out["valid"], out)
        self.assertEqual((out["trust_level"], out["snapshot_id"]), ("TRUSTED_LOCAL", self.m["snapshot_id"]))
        b["expect"]["require_trust"] = "ISOLATED_VERIFIED"
        p.write_text(json.dumps(b))
        out = json.loads(subprocess.run(["node", str(Path(__file__).resolve().parents[1] / "conformance" / "node" / "verify.mjs"), "bundle", str(p)], capture_output=True, text=True).stdout)
        self.assertEqual(out["code"], "TRUST_INSUFFICIENT")

    def test_new_machinery_works_on_a_migrated_workspace(self):
        ws = Workspace(self.root)
        self.assertEqual(controller.list_jobs(ws), [])
        j = controller.enqueue(ws, self.m["candidate_id"])  # already CERTIFIED: the job is recorded but there is nothing to run
        self.assertEqual(j["state"], "QUEUED")

    def test_a_newer_database_is_refused(self):
        ws = Workspace(self.root)
        with ws.db.tx() as c:
            c.execute("update meta set value=? where key='schema_version'", (str(versions.DB_SCHEMA_VERSION + 1),))
        with self.assertRaises(SchemaError):
            Workspace(self.root)


class OlderLayoutTests(unittest.TestCase):
    def test_the_0_3_0_layout_migrates_all_the_way_to_current(self):
        fx = Path(__file__).parent / "fixtures" / "schema_v030.sql"
        tmp = Path(tempfile.mkdtemp())
        self.addCleanup(shutil.rmtree, tmp, True)
        (tmp / ".vep").mkdir()
        c = sqlite3.connect(str(tmp / ".vep" / "vep.db"))
        c.executescript(fx.read_text())
        c.commit(); c.close()
        ws = Workspace(tmp)
        with ws.db.read() as cx:
            self.assertEqual(int(cx.execute("select value from meta where key='schema_version'").fetchone()[0]), versions.DB_SCHEMA_VERSION)
            self.assertIsNotNone(cx.execute("select name from sqlite_master where name='jobs'").fetchone())
